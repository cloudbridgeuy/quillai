import { expect, test } from "../app/node_modules/@playwright/test/index.js";
import { expectEditorReady } from "./editor-ready";

test("lore modal discards drafts, restores focus, and confirms deletion", async ({ page, request }) => {
  const api = process.env.QUILLAI_E2E_API_URL;
  if (!api) throw new Error("Run with cargo xtask e2e");
  const series = await (await request.post(`${api}/series`, { data: { title: "Lore modal", position: 0 } })).json();
  const base = `${api}/series/${series.id}`;
  const book = await (await request.post(`${base}/books`, { data: { title: "Book", position: 0 } })).json();
  const chapter = await (await request.post(`${base}/books/${book.id}/chapters`, { data: { title: "Chapter", position: 0, kind: "chapter" } })).json();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/?${new URLSearchParams({ apiBaseUrl: api, seriesId: String(series.id), bookId: String(book.id), chapterId: String(chapter.id) })}`);
  await expectEditorReady(page.locator(".ql-editor"));
  await page.getByRole("button", { name: "Manuscript", exact: true }).click();
  const lore = page.getByRole("region", { name: "Series lore", exact: true });
  const newButton = lore.getByRole("button", { name: "New lore", exact: true });
  await newButton.click();
  const create = page.getByRole("dialog", { name: "Create lore", exact: true });
  await expect(create).toBeVisible();
  await expect(create.locator("form")).toBeVisible();
  await expect(create.getByRole("button", { name: /cancel/i })).toHaveCount(0);
  await create.getByLabel("Kind").selectOption("place");
  await create.getByLabel("Name", { exact: true }).fill("Discarded");
  await create.getByLabel("Keywords (one per line)").fill("keyword");
  await create.getByLabel("Aliases (one per line)").fill("alias");
  await create.getByLabel("Visible text (AI context)").fill("visible");
  await create.getByLabel("Hidden notes — author-only, never sent to AI").fill("hidden");
  await create.getByLabel("In AI requests").selectOption("leave_out");
  await create.getByLabel("Pin in AI context").check();
  await page.keyboard.press("Escape");
  await expect(create).toHaveCount(0);
  await expect(newButton).toBeFocused();
  expect(await (await request.get(`${base}/lore`)).json()).toEqual([]);
  await newButton.click();
  await expect(create.getByLabel("Kind")).toHaveValue("character");
  for (const label of ["Name", "Keywords (one per line)", "Aliases (one per line)", "Visible text (AI context)", "Hidden notes — author-only, never sent to AI"]) {
    await expect(create.getByLabel(label, { exact: true })).toHaveValue("");
  }
  await expect(create.getByLabel("In AI requests")).toHaveValue("include");
  await expect(create.getByLabel("Pin in AI context")).not.toBeChecked();
  await create.getByLabel("Name", { exact: true }).fill("Mira");
  await create.getByRole("button", { name: "Save lore", exact: true }).click();
  const entry = lore.getByRole("button", { name: "Mira · character", exact: true });
  await expect(entry).toBeVisible();
  await entry.click();
  const edit = page.getByRole("dialog", { name: "Edit lore", exact: true });
  await edit.getByRole("button", { name: "Delete lore", exact: true }).click();
  await expect(edit.getByRole("button", { name: "Confirm delete", exact: true })).toBeVisible();
  expect(await (await request.get(`${base}/lore`)).json()).toHaveLength(1);
  await page.keyboard.press("Escape");
  await expect(entry).toBeFocused();
  await expect(entry).toBeVisible();
  await entry.click();
  await expect(edit.getByRole("button", { name: "Delete lore", exact: true })).toBeVisible();
  await edit.getByRole("button", { name: "Delete lore", exact: true }).click();
  await edit.getByRole("button", { name: "Confirm delete", exact: true }).click();
  await expect(lore.getByText("No lore yet.", { exact: true })).toBeVisible();
  expect(await (await request.get(`${base}/lore`)).json()).toEqual([]);
});
